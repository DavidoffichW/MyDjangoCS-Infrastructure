"""Minimal ownership protocol accepted by optional binary staging."""

from contextlib import AbstractContextManager
from typing import Protocol


class BorrowToken(Protocol):
    def read(self, offset: int = 0, length: int | None = None) -> bytes: ...
    def write(self, offset: int, data: bytes) -> None: ...


class MemoryArenaProtocol(Protocol):
    def allocate(self, element_type: str, count: int): ...
    def exclusive(self, handle) -> AbstractContextManager[BorrowToken]: ...
    def shared(self, handle) -> AbstractContextManager[BorrowToken]: ...
    def seal(self, handle) -> bytes: ...
    def release(self, handle) -> None: ...
